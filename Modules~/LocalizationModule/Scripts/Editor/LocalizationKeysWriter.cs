#if UNITY_EDITOR

using System.Collections.Generic;
using System.IO;
using System.Text;
using UnityEditor;

namespace Modules.LocalizationModule.Editor
{
    /// <summary>
    /// Writes LocalizationKeys.cs - one constant per key of the Game table - so a Command reads
    /// <c>_localization.Get(LocalizationKeys.POPUP_AD_WATCH)</c> and a key mistyped or deleted is a
    /// compile error rather than a missing text on the device. The file is rewritten only when its
    /// contents change, so a pass that adds nothing does not recompile the project.
    /// </summary>
    internal class LocalizationKeysWriter
    {
        private const string FILE = "LocalizationKeys";

        /// <summary><c>popup.ad.watch</c> is POPUP_AD_WATCH; a key starting with a digit gets a leading underscore.</summary>
        public string ConstantOf(string key)
        {
            var name = new StringBuilder();
            bool gap = false;

            foreach (char c in key)
            {
                if (char.IsLetterOrDigit(c))
                {
                    if (gap && name.Length > 0)
                        name.Append('_');

                    name.Append(char.ToUpperInvariant(c));
                    gap = false;
                }
                else
                {
                    gap = true;
                }
            }

            if (name.Length == 0 || char.IsDigit(name[0]))
                name.Insert(0, '_');

            return name.ToString();
        }

        /// <summary>The file's text. Two keys that make the same constant keep the first; the second gets a number.</summary>
        public string Source(IEnumerable<string> keys)
        {
            var taken = new HashSet<string>();
            var source = new StringBuilder();

            source.AppendLine("// Generated by the Localization panel from the Game table. Generate keys rewrites it whole.");
            source.AppendLine("namespace Modules.LocalizationModule.Constants");
            source.AppendLine("{");
            source.AppendLine("    public static class LocalizationKeys");
            source.AppendLine("    {");

            foreach (string key in keys)
            {
                string name = ConstantOf(key);

                for (int n = 2; !taken.Add(name); n++)
                    name = ConstantOf(key) + "_" + n;

                source.AppendLine($"        public const string {name} = \"{key.Replace("\\", "\\\\").Replace("\"", "\\\"")}\";");
            }

            source.AppendLine("    }");
            source.AppendLine("}");

            return source.ToString();
        }

        /// <summary>True when the file changed and the project will recompile.</summary>
        public bool Write(IEnumerable<string> keys)
        {
            string path = PathOfFile();

            if (path == null)
                return false;

            string source = Source(keys);

            if (File.Exists(path) && File.ReadAllText(path).Replace("\r\n", "\n") == source.Replace("\r\n", "\n"))
                return false;

            File.WriteAllText(path, source);
            AssetDatabase.ImportAsset(path);

            return true;
        }

        private string PathOfFile()
        {
            foreach (string guid in AssetDatabase.FindAssets(FILE + " t:MonoScript"))
            {
                string path = AssetDatabase.GUIDToAssetPath(guid);

                if (Path.GetFileNameWithoutExtension(path) == FILE)
                    return path;
            }

            return null;
        }
    }
}

#endif
